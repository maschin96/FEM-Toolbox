"""Immutable coupling metadata; FEM topology is checked by future adapters."""

from __future__ import annotations

import re
from dataclasses import dataclass

from fem_toolbox.errors import ValidationError


def _name(value: str) -> str:
    if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", value):
        raise ValidationError("invalid port name", field="ports.name")
    return value.lower()


def _selection(value: str) -> str:
    if not isinstance(value, str) or not value or value.strip() != value:
        raise ValidationError(
            "need nonempty FEM selection identifier", field="ports.selection"
        )
    return value


@dataclass(frozen=True, slots=True)
class ElectricalPort:
    """One circuit node / FEM conductor: potential V, charge C, inward current A."""

    name: str
    node: str
    electrode: str

    def __post_init__(self) -> None:
        object.__setattr__(self, "name", _name(self.name))
        if not isinstance(self.node, str) or not re.fullmatch(
            r"[A-Za-z0-9_]+", self.node
        ):
            raise ValidationError("invalid port node", field="ports.node")
        object.__setattr__(self, "node", self.node.lower())
        object.__setattr__(self, "electrode", _selection(self.electrode))


@dataclass(frozen=True, slots=True)
class ThermalPort:
    """Named FEM region receiving the full Joule power of the listed resistors.

    Components are owned normalized names. Region existence/transfer weights
    belong to the coupled adapter. No heat source is generated by this metadata.
    """

    name: str
    region: str
    components: tuple[str, ...]

    def __post_init__(self) -> None:
        object.__setattr__(self, "name", _name(self.name))
        object.__setattr__(self, "region", _selection(self.region))
        if (
            not isinstance(self.components, (list, tuple))
            or not self.components
            or any(
                not isinstance(c, str) or not re.fullmatch(r"[Rr][A-Za-z0-9_]*", c)
                for c in self.components
            )
        ):
            raise ValidationError(
                "thermal port needs resistor names", field="ports.components"
            )
        names = tuple(sorted(c.upper() for c in self.components))
        if len(set(names)) != len(names):
            raise ValidationError(
                "duplicate thermal components", field="ports.components"
            )
        object.__setattr__(self, "components", names)
